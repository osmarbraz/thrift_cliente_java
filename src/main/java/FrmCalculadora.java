    public void calcular() {
        String host = jTHost.getText();
        int porta = Integer.parseInt(jTPorta.getText());

        try {
            //Conecta com o servidor
            TTransport transport = new TSocket(host, porta);
            //Abre a conexao com o servidor            
            transport.open();
            //Cria o protocolo    
            TProtocol protocol = new TBinaryProtocol(transport);
            //Recupera o cliente
            CalculadoraService.Client cliente = new CalculadoraService.Client(protocol);

            //Recupera os valores das caixa de texto
            double n1 = Double.parseDouble(jTNumero1.getText());
            double n2 = Double.parseDouble(jTNumero2.getText());

            //Recupera o resultado
            double resultado = 0;
            if (jRMultiplicar.isSelected()) {
                resultado = cliente.multiplicar(n1, n2);
            } else {
                if (jRDividir.isSelected()) {
                    resultado = cliente.dividir(n1, n2);
                } else {
                    if (jRSomar.isSelected()) {
                        resultado = cliente.somar(n1, n2);
                    } else {
                        if (jRSubtrair.isSelected()) {
                            resultado = cliente.subtrair(n1, n2);
                        }
                    }
                }
            }
            //Coloca o resultado
            jLResultado.setText("" + resultado);
            //Fecha a conexao
            transport.close();
        } catch (TException x) {
            x.printStackTrace();
        }
    }
